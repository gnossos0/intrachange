/**
 * Returns the esoteric target info for a given piece and hexNum using the nested lookup structure.
 * @param {string} piece - Piece code (e.g. 'BP', 'WK')
 * @param {number} hexNum - The hexagram number of the current square
 * @returns {object|null} { hexNum, row, col, coord } or null if no esoteric move
 */

export function getEsotericTargetIndex(pieceCode, hexNum) {
  console.log('[esotericMoves] getEsotericTargetIndex called:', { pieceCode, hexNum });
  const move = esotericMoves.find(m => m.piece === pieceCode && m.hexNum === hexNum);
  if (!move) {
    console.log('[esotericMoves] No esoteric move found for', { pieceCode, hexNum });
    return null;
  }
  console.log('[esotericMoves] Esoteric target index:', move.esotericTarget);
  return move.esotericTarget;
}
export function handleEsotericMove(pieceCode, hexNum, boardState) {
  console.log('[esotericMoves] handleEsotericMove called:', { pieceCode, hexNum });
  const esotericTarget = getEsotericTargetIndex(pieceCode, hexNum);
  if (esotericTarget === null) {
    console.log('[esotericMoves] No esoteric target for', { pieceCode, hexNum });
    return boardState; // no change
  }

  const currentPos = positionMap.find(pos => pos.index === hexNum);
  const targetPos = positionMap.find(pos => pos.index === esotericTarget);

  if (!currentPos || !targetPos) {
    console.log('[esotericMoves] Invalid current or target position:', { currentPos, targetPos });
    return boardState; // no change
  }

  // If the target already has the piece, or the move is a no-op, return the original state
  if (
    boardState[targetPos.row][targetPos.col] === pieceCode &&
    boardState[currentPos.row][currentPos.col] === null
  ) {
    console.log('[esotericMoves] No-op move detected, returning original state');
    return boardState;
  }

  // Deep copy the board state
  const newState = boardState.map(row => row.slice());

  // Move piece to esoteric target
  newState[currentPos.row][currentPos.col] = null;
  newState[targetPos.row][targetPos.col] = pieceCode;

  console.log('[esotericMoves] Piece moved to esoteric target:', { from: currentPos, to: targetPos });
  return newState;
}