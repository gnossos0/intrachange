// Helper: get esoteric target for a given piece and hexNum using the nested lookup structure
export function getEsotericTarget(piece, hexNum) {
  console.log('[esotericMoves] getEsotericTarget called:', { piece, hexNum });
  const entry = esotericMovesByHexNum[hexNum]?.[piece];
  if (!entry || entry.esotericTarget == null) {
    console.log('[esotericMoves] No esoteric entry found for', { piece, hexNum });
    return null;
  }
  const target = positionMap.find(p => p.hexNum === entry.esotericTarget);
  if (!target) {
    console.log('[esotericMoves] No target found for esotericTarget:', entry.esotericTarget);
    return null;
  }
  console.log('[esotericMoves] Esoteric target found:', { piece, hexNum, target });
  return {
    hexNum: entry.esotericTarget,
    row: target.row,
    col: target.col,
    coord: target.coord
  };
}
